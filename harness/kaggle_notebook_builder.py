"""Standalone Kaggle Submission Notebook Builder for Code Competitions.

Exports a standalone offline notebook for assembling precomputed prediction
artifacts. Checkpoint-specific inference must be implemented separately; a
missing prediction artifact stops execution rather than fabricating predictions.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional


def build_kaggle_submission_notebook(
    exp_dir: str | Path,
    output_path: str | Path,
    offline_wheels_pattern: Optional[str] = None,
    test_path_override: Optional[str] = None,
    id_column: Optional[str] = None,
    target_column: Optional[str] = None,
) -> Dict[str, Any]:
    """Export precomputed CSV assembly; validate IDs before writing submission.csv.

    This exporter does not implement model-specific checkpoint inference. The
    generated notebook raises when no usable prediction CSV is attached.
    """
    exp_dir = Path(exp_dir).resolve()
    output_path = Path(output_path).resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    exp_id = exp_dir.name
    id_col = id_column or "id"
    target_col = target_column or "target"

    cells: List[Dict[str, Any]] = []

    # Cell 0: Markdown Header
    cells.append({
        "cell_type": "markdown",
        "metadata": {},
        "source": [
            f"# Kaggle Code Competition Submission: {exp_id}\n",
            "Auto-generated by **AI-Harness Standalone Notebook Exporter**.\n",
            "- **Execution Mode:** Offline precomputed prediction assembly\n",
            f"- **Artifact Directory:** `{exp_id}`\n",
            "Checkpoint inference is model-specific. Implement it before assembly when the competition requires fresh inference; missing predictions stop execution.\n",
        ],
    })

    # Cell 1: Offline Wheel Installer
    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [
            "# 1. Install Offline Wheels for Air-Gapped Environments\n",
            "import glob, os, subprocess, sys\n",
            f"wheel_patterns = {[offline_wheels_pattern] if offline_wheels_pattern else ['/kaggle/input/**/offline_wheels/*.whl', '/kaggle/input/**/*.whl']!r}\n",
            "wheels = sorted({p for pattern in wheel_patterns for p in glob.glob(pattern, recursive=True)})\n",
            "if wheels:\n",
            "    print(f'Installing {len(wheels)} offline dependency wheel(s)...')\n",
            "    subprocess.run([sys.executable, '-m', 'pip', 'install', '--no-index', '--no-deps', *wheels], check=True)\n",
            "    print('Offline wheels installed successfully.')\n",
            "else:\n",
            "    print('No offline wheels detected; proceeding with environment defaults.')\n",
        ],
    })

    # Cell 2: Imports & Environment Verification
    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [
            "# 2. Standard Imports\n",
            "import os, sys, glob, json\n",
            "import pandas as pd\n",
            "import numpy as np\n",
            "print('Python runtime:', sys.version.split()[0])\n",
            "print('Working directory:', os.getcwd())\n",
        ],
    })

    # Cell 3: Test Dataset Discovery
    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [
            "# 3. Discover Test Dataset\n",
            f"target_id_col = {id_col!r}\n",
            f"target_pred_col = {target_col!r}\n",
            f"test_path_override = {test_path_override!r}\n",
            "test_files = [test_path_override] if test_path_override else sorted(set(glob.glob('/kaggle/input/**/test.csv', recursive=True) + glob.glob('/kaggle/input/**/test.parquet', recursive=True)))\n",
            "if not test_files:\n",
            "    # Fallback paths for local verification\n",
            "    test_files = [p for p in ['dataset/test.csv', 'test.csv'] if os.path.exists(p)]\n",
            "\n",
            "if not test_files:\n",
            "    raise FileNotFoundError('Could not locate test dataset under /kaggle/input/')\n",
            "if len(test_files) != 1:\n",
            "    raise ValueError('Multiple test datasets found; set test_path_override explicitly')\n",
            "\n",
            "test_path = test_files[0]\n",
            "print(f'Loading test dataset from: {test_path}')\n",
            "test_df = pd.read_csv(test_path) if test_path.endswith('.csv') else pd.read_parquet(test_path)\n",
            "print(f'Loaded test shape: {test_df.shape}')\n",
        ],
    })

    # Cell 4: Precomputed Candidate Assembly
    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [
            "# 4. Assemble existing predictions; model-specific inference is not implemented here\n",
            f"art_candidates = glob.glob({'/kaggle/input/**/' + exp_id + '/**/*'!r}, recursive=True)\n",
            "print(f'Found {len(art_candidates)} candidate artifact file(s) in attached datasets.')\n",
            "\n",
            "def require_ids(frame, name):\n",
            "    if target_id_col not in frame or frame[target_id_col].isna().any() or frame[target_id_col].duplicated().any():\n",
            "        raise ValueError(f'{name} requires unique, non-null IDs in {target_id_col!r}')\n",
            "require_ids(test_df, 'Test dataset')\n",
            "pred_files = sorted(set(p for p in art_candidates if p.endswith('test_predictions.csv')))\n",
            "if not pred_files:\n",
            "    pred_files = sorted(set(p for p in art_candidates if p.endswith('submission.csv')))\n",
            "if not pred_files:\n",
            f"    pred_files = [p for p in {[str(exp_dir / 'test_predictions.csv'), str(exp_dir / 'submission.csv')]!r} if os.path.isfile(p)][:1]\n",
            "if not pred_files:\n",
            "    raise FileNotFoundError('No prediction CSV found. Attach test_predictions.csv or implement model-specific inference before assembly.')\n",
            "if len(pred_files) != 1:\n",
            "    raise ValueError('Multiple prediction artifacts found; attach only the intended experiment predictions')\n",
            "print(f'Aligning predictions from artifact: {pred_files[0]}')\n",
            "cand_df = pd.read_csv(pred_files[0])\n",
            "require_ids(cand_df, 'Prediction artifact')\n",
            "if set(cand_df[target_id_col]) != set(test_df[target_id_col]):\n",
            "    raise ValueError('Prediction IDs do not match the test dataset')\n",
            "source_col = target_pred_col if target_pred_col in cand_df else 'pred_' + target_pred_col\n",
            "if source_col not in cand_df:\n",
            "    raise ValueError(f'Prediction artifact lacks target {target_pred_col!r}; set the intended target column explicitly')\n",
            "sub = test_df[[target_id_col]].merge(cand_df[[target_id_col, source_col]], on=target_id_col, how='left', validate='one_to_one')\n",
            "sub = sub.rename(columns={source_col: target_pred_col})\n",
        ],
    })

    # Cell 5: Sanity Verification & Submission Output
    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [
            "# 5. Sanity Checks & Write submission.csv\n",
            "assert not sub.empty, 'Submission dataframe is empty'\n",
            "assert not sub.isna().any().any(), 'Submission contains NaN values'\n",
            "assert len(sub) == len(test_df), f'Row mismatch: {len(sub)} vs {len(test_df)}'\n",
            "if pd.api.types.is_numeric_dtype(sub[target_pred_col]) and not np.isfinite(sub[target_pred_col]).all():\n",
            "    raise ValueError('Submission predictions must be finite')\n",
            "\n",
            "sub.to_csv('submission.csv', index=False)\n",
            "print('SUCCESS: submission.csv written successfully!')\n",
            "print(f'Shape: {sub.shape}')\n",
            "print(sub.head())\n",
        ],
    })

    notebook = {
        "cells": cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "version": "3.10.0",
            },
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }

    output_path.write_text(json.dumps(notebook, indent=2, ensure_ascii=False), encoding="utf-8")
    return {
        "status": "SUCCESS",
        "notebook_path": str(output_path),
        "cell_count": len(cells),
        "exp_id": exp_id,
    }
